"""Print the per-month tie-out table and write TIEOUT.md.

Checks, each recomputed here rather than read from the build:
1. The published 12-month change, recomputed from the raw flat file line for
   WPUFD4 (not the cached indexes.json).
2. Items vs published, every month from October 2016, with the reason a month
   is out of the page.
3. The page: the drawn pieces (items plus the gray gap piece) add up to the
   published change in every month it shows.
4. Restored weights (items BLS printed as 0.000) against the value BLS printed
   for the same December one file later, where it did.
"""
from __future__ import annotations

import csv
import json

from chain import Inputs
from common import DIST, PROCESSED, ROOT, WP
from weights import read_file


def raw_fd4():
    out = {}
    for p in sorted(WP.glob("wp.data.*")):
        for line in open(p):
            if line.startswith("WPUFD4 ") or line.startswith("WPUFD4\t"):
                f = line.rstrip("\n").split("\t")
                if f[2].startswith("M") and f[2] != "M13":
                    out[f"{f[1]}-{f[2][1:]}"] = float(f[3])
    return out


def main():
    rows = list(csv.DictReader(open(PROCESSED / "monthly_summary.csv")))
    fd = raw_fd4()
    lines = ["| Month | Published 12-mo % | Items sum | Gap (pts) | BLS rounds to | Filled weight % | Status | Why out |",
             "|---|---:|---:|---:|---:|---:|---|---|"]
    print(f"{'month':8} {'published':>9} {'items':>8} {'gap':>8} {'1dp':>5} {'filled%':>7}  status")
    bad_raw = []
    for r in rows:
        t = r["month"]
        b = f"{int(t[:4]) - 1}{t[4:]}"
        raw = (fd[t] / fd[b] - 1) * 100
        if abs(raw - float(r["published"])) > 0.0001:
            bad_raw.append(t)
        flag = r["status"] + (" (P)" if r["preliminary"] == "True" else "")
        print(f"{t:8} {float(r['published']):9.3f} {float(r['items']):8.3f} {float(r['gap']):+8.4f} "
              f"{float(r['published_1dp']):5.1f} {float(r['filled_share']):7.2f}  {flag:9} {r['why_out']}")
        lines.append(f"| {t} | {float(r['published']):.3f} | {float(r['items']):.3f} | {float(r['gap']):+.4f} | "
                     f"{float(r['published_1dp']):.1f} | {float(r['filled_share']):.2f} | {flag} | {r['why_out']} |")
    passing = [r for r in rows if r["status"] == "pass"]
    gaps = [abs(float(r["gap"])) for r in passing]
    pre = [r for r in rows if r["why_out"].startswith("one-decimal")]
    pre_over = sum(abs(float(r["gap"])) > 0.05 for r in pre)
    summary = (f"{len(passing)} of {len(rows)} months pass ({passing[0]['month']} to {passing[-1]['month']}). "
               f"Passing months: mean absolute gap {sum(gaps)/len(gaps):.4f} points, largest {max(gaps):.4f}; "
               f"{sum(g <= 0.02 for g in gaps)} within 0.02. One-decimal months ({len(pre)}): "
               f"{pre_over} miss by more than 0.05.")
    print("\n" + summary)
    print("raw FD4 recompute:", "matches every month" if not bad_raw else f"MISMATCH {bad_raw}")

    # The page payload
    page = json.loads((PROCESSED / "page_data.json").read_text())
    worst = 0.0
    for t in page["order"]:
        M = page["months"][t]
        drawn = sum(r[1] for r in M["r"] if r) + M["gap"]
        worst = max(worst, abs(drawn - M["pub"]))
    print(f"page: {len(page['order'])} months; drawn pieces vs published, largest difference {worst:.5f}")

    # Restored weights vs BLS's later printing
    inp = Inputs()
    rest_lines = []
    for y in (2019, 2021, 2024):
        later = {c: d for c, n, d, e in read_file(y + 2)["items"]} if y + 2 <= 2026 else {}
        for c, w in inp.tree(y)["restored"].items():
            lv = later.get(c)
            rest_lines.append(f"| Dec {y} | {c} | {w:.4f} | {'' if lv is None else f'{lv:.3f}'} |")
            print(f"restored Dec {y} {c}: ours {w:.4f}, BLS later printed {lv}")

    md = ["# Tie-out", "",
          "Generated by `scripts/tieout.py`. Rules are in `scripts/monthly.py` and DATASETS.md.", "",
          "## Summary", "", summary, "",
          f"Published 12-month change recomputed from the raw flat file: {'matches every month' if not bad_raw else bad_raw}.",
          f"Page: drawn pieces (items plus the gray gap piece) vs published, largest difference {worst:.5f} points.", "",
          "## Restored weights", "", "Items BLS printed as 0.000 in a short December, given their prior December weight rolled forward,",
          "compared with what BLS printed for the same December in the next year's file (blank where it printed a dash).", "",
          "| December | Code | Ours | BLS later |", "|---|---|---:|---:|", *rest_lines, "",
          "## Every month", "", "(P) = preliminary; BLS revises the last four months.", "", *lines, ""]
    (ROOT / "TIEOUT.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
